# corpus/forward-connector.yaml:
# `buildForwardScenario("logs", "logs")` (`test/forward-connector.test.ts`).
FORWARD_CONNECTOR = r'''# OpenTelemetry Collector Configuration
# Generated by Telflo

receivers:
  otlp:
    protocols:
      grpc:
        endpoint: 'localhost:4317'
      http:
        endpoint: 'localhost:4318'
exporters:
  otlp:
    endpoint: 'otelcol:4317'
    timeout: '5s'
    compression: 'gzip'
    tls:
      insecure: true
connectors:
  forward: {}
service:
  pipelines:
    logs/in:
      receivers: [otlp]
      exporters: [forward]
    logs/out:
      receivers: [forward]
      exporters: [otlp]
'''


def forward_scenario(in_signal: str, out_signal: str) -> str:
    """`buildForwardScenario(in_signal, out_signal)`'s text: the corpus's,
    its two pipelines renamed (the generator writes nothing else that
    depends on the signals)."""
    return FORWARD_CONNECTOR.replace("    logs/in:\n", f"    {in_signal}/in:\n").replace(
        "    logs/out:\n", f"    {out_signal}/out:\n"
    )
